"""Writes src/TopDownShooter/Assets/legs_walk.svg: the soldier's walk cycle, seen from above.

8 frames side by side, each a 768x512 cell at 400 px per world unit, facing right, with the
soldier's center (hips) at (384, 256) of the cell. The cells are wider than tall so a long stride
fits without touching the next frame. Only legs and boots are drawn: the torso
sprite covers the hips, so what shows is the boots and trousers stepping out in front and behind.

The soldier walks in a bladed stance, as when aiming: the left foot is biased forward and the right
foot back, which also keeps the boots out from under the rifle so the steps can be seen. Frame 0 is
the passing position (feet at their resting spots), which doubles as the standing pose. Each foot
swings forward and back along a sine curve around its resting spot, the two feet half a cycle apart. The foot moving forward
is in the air, so it's drawn slightly larger and lighter (closer to the camera).

Run, then export:  python tools/make_walk_sheet.py && python tools/export_art.py legs
"""
import math
from pathlib import Path

FRAMES = 8
CELL_WIDTH, CELL_HEIGHT = 768, 512
HIP_X, HIP_Y = 384, 256
STRIDE = 140      # px: how far each foot swings ahead of and behind the hips
HIP_SPREAD = 70   # px: each leg's distance from the center line
STANCE = 60       # px: the left foot rests this far ahead of the hips, the right foot this far behind
BOOT_SCALE = 1.2
OUT = Path(__file__).resolve().parent.parent / "src" / "TopDownShooter" / "Assets" / "legs_walk.svg"


def leg(x_foot: float, y: float, lift: float) -> str:
    """One leg: the trouser from the hip to the ankle, then the boot. `lift` is 0 on the ground, up to 1 mid-swing."""
    scale = BOOT_SCALE * (1 + 0.07 * lift)
    shade = f"{0.10 * lift:.3f}"
    return f"""
    <g>
      <path d="M{HIP_X},{y} L{x_foot - 30:.1f},{y}" stroke="#2e3226" stroke-width="84" stroke-linecap="round"/>
      <path d="M{HIP_X},{y} L{x_foot - 30:.1f},{y}" stroke="#686e56" stroke-width="76" stroke-linecap="round"/>
      <path d="M{HIP_X},{y - 14} L{x_foot - 30:.1f},{y - 14}" stroke="#80876b" stroke-width="18" stroke-linecap="round" opacity="0.6"/>
      <g transform="translate({x_foot:.1f} {y}) scale({scale:.3f})">
        <use href="#boot"/>
        <rect x="-55" y="-40" width="176" height="80" rx="40" fill="#fff" opacity="{shade}"/>
      </g>
    </g>"""


def frame(index: int) -> str:
    phase = 2 * math.pi * index / FRAMES
    offset = STRIDE * math.sin(phase)
    # The left foot (top of the image) leads; the right foot is half a cycle behind.
    # A foot is in the air while it moves forward, which is when the sine is rising (cosine > 0).
    left_lift = max(0.0, math.cos(phase))
    right_lift = max(0.0, -math.cos(phase))
    legs = (leg(HIP_X + STANCE + offset, HIP_Y - HIP_SPREAD, left_lift)
            + leg(HIP_X - STANCE - offset, HIP_Y + HIP_SPREAD, right_lift))
    return f"""
  <g transform="translate({index * CELL_WIDTH} 0)" filter="url(#shadow)">{legs}
  </g>"""


def main() -> None:
    frames = "".join(frame(i) for i in range(FRAMES))
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{FRAMES * CELL_WIDTH}" height="{CELL_HEIGHT}" viewBox="0 0 {FRAMES * CELL_WIDTH} {CELL_HEIGHT}">
  <!-- Generated by tools/make_walk_sheet.py: change STRIDE, HIP_SPREAD or the boot there and run it again.
       Walk cycle, {FRAMES} frames of {CELL_WIDTH}x{CELL_HEIGHT} px, facing right, hips at ({HIP_X}, {HIP_Y}) of each cell. -->
  <defs>
    <!-- Trousers are flat colors with a highlight stroke: a gradient on a perfectly horizontal line
         has a zero-height bounding box, and browsers then don't paint it at all. -->
    <linearGradient id="leather" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#8f7a58"/>
      <stop offset="0.5" stop-color="#7a6646"/>
      <stop offset="1" stop-color="#5a4a32"/>
    </linearGradient>
    <!-- A boot centered on its ankle, toe pointing right: sole outline, upper, toe cap, laces. -->
    <g id="boot">
      <rect x="-55" y="-40" width="176" height="80" rx="40" fill="#2a241b"/>
      <rect x="-50" y="-35" width="166" height="70" rx="35" fill="url(#leather)"/>
      <path d="M70,-33 Q118,-33 118,0 Q118,33 70,33 Z" fill="#6c5a3e"/>
      <rect x="-44" y="-22" width="34" height="44" rx="14" fill="#5f4f37"/>
      <path d="M4,-12 H62 M4,12 H62" stroke="#3a3024" stroke-width="3" stroke-linecap="round"/>
      <path d="M10,-12 L22,12 M22,-12 L34,12 M34,-12 L46,12 M46,-12 L58,12" stroke="#3a3024" stroke-width="2.5" stroke-linecap="round"/>
    </g>
    <filter id="shadow" x="-10%" y="-20%" width="120%" height="140%">
      <feDropShadow dx="4" dy="7" stdDeviation="6" flood-color="#000" flood-opacity="0.4"/>
    </filter>
  </defs>
{frames}
</svg>
"""
    OUT.write_text(svg, encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
